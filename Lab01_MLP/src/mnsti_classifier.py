import torch
import torch.nn as nn
import torchvision
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from torch.utils.data import TensorDataset, DataLoader
from src.config import EPOCHS, BATCH_SIZE, LR, OPTIMIZER_DICT, OPTIM
from src.utils import train, evaluation, preprocess

########### NEURAL NET DEFINITION ##############

class NeuralNetMLP(nn.Module):
  def __init__(self):
    super().__init__()
    self.network = nn.Sequential(
        # First hidden layer
        nn.Linear(in_features=784, out_features=128),
        nn.ReLU(),

        # Second hidden layer
        nn.Linear(in_features=128, out_features=64),
        nn.ReLU(),

        # Output layer (without Softmax Layer due to CrossEntropyLoss conflict)
        nn.Linear(in_features=64, out_features=10)
    )

  def forward(self, X):
    return self.network(X)
###################################################

dataset_train = torchvision.datasets.MNIST(
    root='./data',
    train=True,
    download=True
)

dataset = preprocess(dataset_train)

batches = DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=True)

model = NeuralNetMLP()
print(model)

########## TRAINING ###############

loss = train(model=model, lr=LR, optim_name=OPTIM, epochs=EPOCHS, batches=batches)

plt.figure()
plt.plot(loss)
plt.title("Training loss")
plt.xticks(ticks=np.arange(0, stop=EPOCHS, step=5))
plt.xlabel("Epochs")
plt.ylabel("Mean loss")
plt.show()

############# EVALUATION ###############

# Train evaluation

accuracy = evaluation(model, dataset)
print(f"Train accuracy: {accuracy:.2f}%")

# Preparing test data

test_dataset = torchvision.datasets.MNIST(
    root='./data',
    train=False,
    download=True
)

test_dataset = preprocess(test_dataset)

accuracy = evaluation(model, test_dataset)

print(f"Test accuracy: {accuracy:.2f} %")